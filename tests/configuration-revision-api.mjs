import assert from 'node:assert/strict';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createHash, randomUUID } from 'node:crypto';
import { resolve, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import Ajv2020 from 'ajv/dist/2020.js';
import addFormats from 'ajv-formats';

let verificationStage = 'load_private_test_sessions';
async function main() {
  const root = new URL('../', import.meta.url);
  const base = process.argv[2] ?? 'http://127.0.0.1:8080/api/v1';
  assert.equal(new URL(base).hostname, '127.0.0.1');
  const sessionDirectory = process.env.MOP_TEST_SESSION_DIRECTORY ? resolve(process.env.MOP_TEST_SESSION_DIRECTORY) : fileURLToPath(new URL('deploy/private/', root));
  if (process.env.MOP_TEST_SESSION_DIRECTORY) assert.ok(process.env.MOP_EVIDENCE_OUTPUT && process.env.MOP_TEST_ENVIRONMENT_NAME, '独立环境必须明确证据输出和环境名称，不能覆盖原环境记录');
  if (process.env.MOP_TEST_SESSION_DIRECTORY) assert.notEqual(resolve(process.env.MOP_EVIDENCE_OUTPUT), fileURLToPath(new URL('docs/evidence/configuration-revision-http.json', root)), '独立环境不得覆盖原环境证据');
  const sessions = Object.fromEntries(['creator', 'reviewer', 'viewer'].map(role => [role, JSON.parse(readFileSync(join(sessionDirectory, `qa-revision-${role}.json`), 'utf8').replace(/^\uFEFF/, ''))]));
  assert.notEqual(sessions.creator.user_id, sessions.reviewer.user_id, '必须两个不同真实OIDC主体');
  const contract = JSON.parse(readFileSync(new URL('contracts/local-api.openapi.json', root), 'utf8'));
  const ajv = new Ajv2020({ strict: false, allErrors: true });
  addFormats(ajv);
  let checked = 0;
  const key = () => randomUUID();
  async function request(role, method, route, { body, rawBody, status = 200, path = route.split('?')[0], idem = key(), csrf } = {}) {
    verificationStage = `${role} ${method} ${path}`;
    const session = sessions[role];
    const headers = { Cookie: session.cookie, 'Idempotency-Key': idem, 'X-CSRF-Token': csrf ?? session.csrf_token, Accept: 'application/json' };
    if (body !== undefined || rawBody !== undefined) headers['Content-Type'] = 'application/json';
    const response = await fetch(base + route, { method, headers, body: rawBody ?? (body === undefined ? undefined : JSON.stringify(body)), redirect: 'manual' });
    const data = await response.json();
    verificationStage += ` actual=${response.status} expected=${status}`;
    assert.equal(response.status, status, `${role} ${method} ${path}: unexpected_status`);
    const schema = contract.paths[path]?.[method.toLowerCase()]?.responses[String(status)]?.content?.['application/json']?.schema;
    assert.ok(schema, `${method} ${path} 缺契约`);
    const validate = ajv.compile({ ...schema, components: contract.components });
    assert.ok(validate(data), `${method} ${path}: contract_response_mismatch`);
    assert.equal(data.trace_id, response.headers.get('x-trace-id'));
    checked++;
    return data;
  }
  const ready = await request('creator', 'GET', '/health/ready');
  assert.equal(ready.data.mode, 'remote_test');
  assert.equal(ready.data.durable, true);
  const creatorSession = (await request('creator', 'GET', '/session')).data;
  assert.equal(creatorSession.user.role, 'padmin');
  const tenantA = creatorSession.allowed_tenants[0].id;
  const tenantB = creatorSession.allowed_tenants[1].id;
  for (const role of ['creator', 'reviewer']) {
    const session = (await request(role, 'POST', '/session/tenant', { body: { tenant_id: tenantA } })).data;
    sessions[role].csrf_token = session.csrf_token;
  }
  const registry = (await request('creator', 'GET', '/configurations')).data.items;
  const definition = registry.find(item => item.key === 'monitor.sample_interval_sec');
  assert.equal(definition.decision_status, 'pending');
  assert.equal(definition.value, null);
  const objectDefinition = registry.find(item => item.type === 'object' && item.decision_status === 'pending');
  assert.ok(objectDefinition);
  const route = `/configurations/${encodeURIComponent(definition.key)}/revisions`;
  const routePath = '/configurations/{key}/revisions';
  const evidence = { reference: `document-ref:test-review-${key()}`, title: '虚构测试书面资料引用，未核验', sha256: createHash('sha256').update('test-only unverified document metadata').digest('hex') };
  const proposal = { proposed_value: 60, reason: '仅测试内部配置修订审批，不形成客户确认。', evidence_refs: [evidence] };
  await request('viewer', 'POST', route, { body: proposal, status: 403, path: routePath });
  await request('creator', 'POST', route, { body: proposal, csrf: 'invalid', status: 403, path: routePath });
  await request('creator', 'POST', route, { body: { ...proposal, tenant_id: tenantB }, status: 400, path: routePath });
  await request('creator', 'POST', route, { body: { ...proposal, proposed_value: null }, status: 400, path: routePath });
  await request('creator', 'POST', route, { body: { ...proposal, evidence_refs: [{ ...evidence, reference: 'https://untrusted.example/document' }] }, status: 400, path: routePath });
  await request('creator', 'POST', route, { body: { ...proposal, evidence_refs: [{ ...evidence, sha256: 'bad' }] }, status: 400, path: routePath });
  await request('creator', 'POST', route, { body: { ...proposal, reason: '😀'.repeat(501) }, status: 400, path: routePath });
  await request('creator', 'POST', '/configurations/business.timezone/revisions', { body: { ...proposal, proposed_value: 'UTC' }, status: 422, path: routePath });
  await request('creator', 'POST', `/configurations/${encodeURIComponent(objectDefinition.key)}/revisions`, { body: { ...proposal, proposed_value: { client_secret: 'not-a-real-credential' } }, status: 400, path: routePath });
  const objectRoute = `/configurations/${encodeURIComponent(objectDefinition.key)}/revisions`;
  const objectBefore = (await request('creator', 'GET', objectRoute, { path: routePath })).data.items.length;
  for (const numericValue of ['{"limit":1e999}', '{"nested":[-1e999]}', '{"OBJECT_STORAGE_SECRET_KEY":"SYNTHETIC-NOT-A-CREDENTIAL"}']) {
    const rawBody = `{"proposed_value":${numericValue},"reason":${JSON.stringify(proposal.reason)},"evidence_refs":${JSON.stringify(proposal.evidence_refs)}}`;
    await request('creator', 'POST', objectRoute, { rawBody, status: 400, path: routePath });
  }
  assert.equal((await request('creator', 'GET', objectRoute, { path: routePath })).data.items.length, objectBefore, '溢出拒绝不应保存提案');
  const createKey = key();
  const created = (await request('creator', 'POST', route, { body: proposal, idem: createKey, path: routePath })).data;
  assert.equal(created.workflow_status, 'DRAFT');
  assert.equal(created.version, 1);
  assert.equal(created.created_by, sessions.creator.user_id);
  assert.equal(created.history.length, 1);
  const replayCreate = (await request('creator', 'POST', route, { body: proposal, idem: createKey, path: routePath })).data;
  assert.equal(replayCreate.id, created.id);
  assert.equal(replayCreate.history.length, 1);
  await request('creator', 'POST', route, { body: { ...proposal, reason: 'different' }, idem: createKey, status: 409, path: routePath });
  const detailRoute = `/configuration-revisions/${created.id}`;
  const detailPath = '/configuration-revisions/{id}';
  await request('reviewer', 'POST', detailRoute + '/submit', { body: { expected_version: 1 }, status: 403, path: detailPath + '/submit' });
  const submitKey = key();
  const submitted = (await request('creator', 'POST', detailRoute + '/submit', { body: { expected_version: 1 }, idem: submitKey, path: detailPath + '/submit' })).data;
  assert.equal(submitted.workflow_status, 'IN_REVIEW');
  assert.equal(submitted.version, 2);
  assert.equal(submitted.history.length, 2);
  const replaySubmit = (await request('creator', 'POST', detailRoute + '/submit', { body: { expected_version: 1 }, idem: submitKey, path: detailPath + '/submit' })).data;
  assert.equal(replaySubmit.version, 2);
  await request('creator', 'POST', detailRoute + '/review', { body: { expected_version: 2, decision: 'approve', comment: '不能自审' }, status: 403, path: detailPath + '/review' });
  await request('reviewer', 'POST', detailRoute + '/review', { body: { expected_version: 1, decision: 'approve', comment: '旧版本' }, status: 409, path: detailPath + '/review' });
  await request('reviewer', 'POST', detailRoute + '/review', { body: { expected_version: 2, decision: 'approve', comment: '无伪造人', reviewed_by: sessions.creator.user_id }, status: 400, path: detailPath + '/review' });
  const reviewBody = { expected_version: 2, decision: 'approve', comment: '测试身份完成内部复核；证据未核验，配置不生效。' };
  const reviewKey = key();
  const approved = (await request('reviewer', 'POST', detailRoute + '/review', { body: reviewBody, idem: reviewKey, path: detailPath + '/review' })).data;
  assert.equal(approved.workflow_status, 'APPROVED');
  assert.equal(approved.reviewed_by, sessions.reviewer.user_id);
  assert.equal(approved.version, 3);
  assert.equal(approved.history.length, 3);
  assert.equal(approved.confirmation_status, 'UNVERIFIED');
  assert.equal(approved.effective_value, null);
  assert.equal(approved.decision_status, 'pending');
  const replayReview = (await request('reviewer', 'POST', detailRoute + '/review', { body: reviewBody, idem: reviewKey, path: detailPath + '/review' })).data;
  assert.equal(replayReview.history.length, 3);
  await request('creator', 'POST', detailRoute + '/withdraw', { body: { expected_version: 3, reason: '终态不能撤回' }, status: 422, path: detailPath + '/withdraw' });
  const registryAfter = (await request('creator', 'GET', '/configurations')).data.items.find(item => item.key === definition.key);
  assert.equal(registryAfter.version, definition.version);
  assert.equal(registryAfter.value, null);
  assert.equal(registryAfter.effective_value, null);
  assert.equal(registryAfter.decision_status, 'pending');
  await request('creator', 'POST', `/configurations/${encodeURIComponent(definition.key)}/publish`, { body: { expected_version: registryAfter.version }, status: 422, path: '/configurations/{key}/publish' });
  const list = (await request('creator', 'GET', route, { path: routePath })).data.items;
  assert.ok(list.some(item => item.id === created.id));
  const otherContext = (await request('reviewer', 'POST', '/session/tenant', { body: { tenant_id: tenantB } })).data;
  sessions.reviewer.csrf_token = otherContext.csrf_token;
  await request('reviewer', 'GET', detailRoute, { status: 404, path: detailPath });
  await request('reviewer', 'POST', detailRoute + '/review', { body: reviewBody, status: 404, path: detailPath + '/review' });
  const otherList = (await request('reviewer', 'GET', route, { path: routePath })).data.items;
  assert.ok(!otherList.some(item => item.id === created.id));
  sessions.reviewer.csrf_token = (await request('reviewer', 'POST', '/session/tenant', { body: { tenant_id: tenantA } })).data.csrf_token;
  const withdrawal = (await request('creator', 'POST', route, { body: { ...proposal, reason: '撤回测试' }, path: routePath })).data;
  const withdrawn = (await request('creator', 'POST', `/configuration-revisions/${withdrawal.id}/withdraw`, { body: { expected_version: 1, reason: '保留已撤回记录' }, path: detailPath + '/withdraw' })).data;
  assert.equal(withdrawn.workflow_status, 'WITHDRAWN');
  assert.equal(withdrawn.history.length, 2);
  const rejection = (await request('creator', 'POST', route, { body: { ...proposal, reason: '拒绝测试' }, path: routePath })).data;
  await request('creator', 'POST', `/configuration-revisions/${rejection.id}/submit`, { body: { expected_version: 1 }, path: detailPath + '/submit' });
  const rejected = (await request('reviewer', 'POST', `/configuration-revisions/${rejection.id}/review`, { body: { expected_version: 2, decision: 'reject', comment: '测试拒绝保留理由。' }, path: detailPath + '/review' })).data;
  assert.equal(rejected.workflow_status, 'REJECTED');
  assert.equal(rejected.history.length, 3);
  const audit = (await request('creator', 'GET', '/audit')).data.items;
  assert.equal(audit.filter(item => item.resource_id === created.id && item.action === 'configuration_revision.approve' && item.result === 'SUCCEEDED').length, 1);
  mkdirSync(new URL('docs/evidence/', root), { recursive: true });
  const summary = { date: new Date().toISOString(), environment: process.env.MOP_TEST_ENVIRONMENT_NAME ?? 'designated-server', mode: 'remote_test', oidc_subjects: 3, http_responses_validated: checked, states_verified: ['DRAFT', 'IN_REVIEW', 'APPROVED', 'REJECTED', 'WITHDRAWN'], self_review_rejected: true, cross_tenant_objects_invisible: true, actor_spoof_rejected: true, replay_has_no_duplicate_history_or_audit: true, registry_unchanged: true, nested_numeric_overflow_rejected_without_revision: true, runtime_storage_secret_field_rejected: true, internal_approval_does_not_confirm_customer_or_activate: true };
  writeFileSync(process.env.MOP_EVIDENCE_OUTPUT ? resolve(process.env.MOP_EVIDENCE_OUTPUT) : new URL('docs/evidence/configuration-revision-http.json', root), JSON.stringify(summary, null, 2) + '\n');
  console.log(JSON.stringify(summary, null, 2));
}

main().catch(() => {
  // Private JSON, protocol and input errors must not echo credentials or document contents.
  console.error(`配置修订真实环境验证失败，步骤：${verificationStage}；未输出秘密或私有输入。`);
  process.exitCode = 1;
});
